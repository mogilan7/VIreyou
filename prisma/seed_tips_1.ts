async function main() {
  for (const t of TIP_CONTENT) {
    await prisma.tipContent.upsert({
      where: { area_lang: { area: t.area, lang: "ru" } }, // требует @@unique([area, lang])
      update: { whyShort: t.whyShort, whyFull: t.whyFull, actionIdea: t.actionIdea, active: true },
      create: { area: t.area, lang: "ru", whyShort: t.whyShort, whyFull: t.whyFull, actionIdea: t.actionIdea, active: true },
    });
  }
  console.log(`Seeded ${TIP_CONTENT.length} TipContent записей.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(async () => { await prisma.$disconnect(); });
