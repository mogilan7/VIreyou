// ── Загрузка ────────────────────────────────────────────────────────────────────
async function main() {
  for (const t of [...EXCESS_TIPS, ...HABIT_TIPS]) {
    await prisma.tipContent.upsert({
      where: { area_kind_lang: { area: t.area, kind: t.kind, lang: "ru" } }, // @@unique([area, kind, lang])
      update: { whyShort: t.whyShort, whyFull: t.whyFull, actionIdea: t.actionIdea, active: true },
      create: { area: t.area, kind: t.kind, lang: "ru", whyShort: t.whyShort, whyFull: t.whyFull, actionIdea: t.actionIdea, active: true },
    });
  }
  for (const p of PATTERN_CONTENT) {
    await prisma.patternContent.upsert({
      where: { patternId_lang: { patternId: p.patternId, lang: "ru" } },
      update: { whyShort: p.whyShort, whyFull: p.whyFull, actionIdea: p.actionIdea, active: true },
      create: { patternId: p.patternId, lang: "ru", whyShort: p.whyShort, whyFull: p.whyFull, actionIdea: p.actionIdea, active: true },
    });
  }
  console.log(`Seeded ${EXCESS_TIPS.length} excess + ${HABIT_TIPS.length} habit + ${PATTERN_CONTENT.length} pattern записей.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(async () => { await prisma.$disconnect(); });
